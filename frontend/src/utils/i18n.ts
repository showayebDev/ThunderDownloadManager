export type SupportedLanguage = 'en' | 'bn' | 'es' | 'fr' | 'de';

export const LANGUAGE_OPTIONS = [
  { value: 'System (English)', code: 'en', label: 'System (English)' },
  { value: 'Bengali', code: 'bn', label: 'বাংলা (Bengali)' },
  { value: 'Spanish', code: 'es', label: 'Español (Spanish)' },
  { value: 'French', code: 'fr', label: 'Français (French)' },
  { value: 'German', code: 'de', label: 'Deutsch (German)' },
] as const;

export function resolveLanguageCode(langStr: string): SupportedLanguage {
  if (!langStr) return 'en';
  const lower = langStr.toLowerCase();
  if (lower.includes('bengali') || lower.includes('bangla') || lower === 'bn') return 'bn';
  if (lower.includes('spanish') || lower.includes('español') || lower === 'es') return 'es';
  if (lower.includes('french') || lower.includes('français') || lower === 'fr') return 'fr';
  if (lower.includes('german') || lower.includes('deutsch') || lower === 'de') return 'de';
  return 'en';
}

